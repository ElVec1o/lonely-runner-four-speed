#!/bin/bash
# split_lines.sh IN_FILE OUT_DIR MODULE PARTSIZE
# Splits the emitted chunk module IN_FILE (LinesN<i>C<c>.lean from `emit`) into parts of PARTSIZE range theorems
# (MODULEp0.lean, MODULEp1.lean, ...) written to OUT_DIR, and writes MODULE.lean there as the aggregator (imports the parts, keeps
# the chunk theorem).  Output is byte-for-byte what the splitting script wrote into the Lean tree (that script wrote
# into the tree itself; this copy takes an output directory so that regeneration never touches the committed sources).
F=$1; D=$2; M=$3; N=$4
mkdir -p "$D"
T=$(mktemp); grep '^theorem lines_' "$F" > "$T"
CH=$(mktemp); sed -n '/^theorem linesChunk_/,/^$/p' "$F" > "$CH"
TOT=$(wc -l < "$T"); P=0; S=1
while [ $S -le $TOT ]; do
  E=$((S+N-1))
  {
    echo "/-"
    echo "# L4S5.${M}p${P} : kernel checks of line loops (part $P of $M, theorems $S..$E)"
    echo "GENERATED by four_e9 emit + splitmod; do not edit."
    echo "-/"
    echo "import LRSpectrumFull.L4S5.LinesChunk"
    echo ""
    echo "namespace LRSpectrumFull"
    echo "namespace L4S5"
    echo ""
    sed -n "${S},${E}p" "$T"
    echo ""
    echo "end L4S5"
    echo "end LRSpectrumFull"
  } > "$D/${M}p${P}.lean"
  P=$((P+1)); S=$((E+1))
done
{
  echo "/-"
  echo "# L4S5.$M : chunk theorem from the parts (generated, split into $P parts)"
  echo "-/"
  for k in $(seq 0 $((P-1))); do echo "import LRSpectrumFull.L4S5.${M}p${k}"; done
  echo ""
  echo "namespace LRSpectrumFull"
  echo "namespace L4S5"
  echo ""
  cat "$CH"
  echo "end L4S5"
  echo "end LRSpectrumFull"
} > "$D/$M.lean"
echo "$M split into $P parts"
rm -f "$T" "$CH"
