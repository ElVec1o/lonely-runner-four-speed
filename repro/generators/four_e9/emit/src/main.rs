// four_e9 emit: line-theorem emitter (E9).  Reads the chunk structure of the Lean data module and the per-record profile and writes
// Lean modules `LinesN<node>C<chunk>.lean` with range theorems `lines_<node>_<chunk>_<lo>_<hi> : linesRangeB ... = true := by decide +kernel`
// and the chunk theorem `linesChunk_<node>_<chunk>` (chain of `linesRange_trans`), plus a manifest TSV.
//
// usage: emit DATA_LEAN PROFILE_TSV OUT_DIR MANIFEST BUDGET MAXREC [node:chunk ...]
//   BUDGET: cost units per range theorem (cost of a record = iters + 0.44*tlscan (memory model 0.36 MB/iter + 0.16 MB/TL entry), a model, calibrated by the probes)
//   MAXREC: maximum number of records in a range theorem (10..30 in the plan)
//   node:chunk selectors; none = all chunks of all nodes.
//   A single record whose cost exceeds BUDGET gets a theorem of its own.
use std::collections::HashMap;
use std::fs;
use std::io::Write;

#[derive(Clone, Debug)]
struct Chunk {
    node: usize,
    idx: usize,
    cnt: usize,
    first: usize, // index of the first record of the chunk inside its node
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    let data = fs::read_to_string(&a[1]).unwrap();
    let prof = fs::read_to_string(&a[2]).unwrap();
    let outdir = &a[3];
    let manifest_path = &a[4];
    let budget: f64 = a[5].parse().unwrap();
    let maxrec: usize = a[6].parse().unwrap();
    let sel: Vec<(usize, usize)> = a[7..].iter().map(|s| {
        let p: Vec<&str> = s.split(':').collect();
        (p[0].parse().unwrap(), p[1].parse().unwrap())
    }).collect();
    // chunk structure of Data.lean: lines "  | k => [" and "    { lo := L, hi := H, cnt := C, bl := ..."
    let mut chunks: Vec<Chunk> = vec![];
    let mut node: Option<usize> = None;
    let mut idx = 0usize;
    let mut first = 0usize;
    for line in data.lines() {
        let t = line.trim_start();
        if let Some(rest) = t.strip_prefix("| ") {
            if let Some(num) = rest.split(" =>").next() {
                if let Ok(n) = num.trim().parse::<usize>() {
                    node = Some(n);
                    idx = 0;
                    first = 0;
                    continue;
                }
            }
        }
        if t.starts_with("{ lo := ") {
            let pos = t.find("cnt := ").unwrap() + 7;
            let cnt: usize = t[pos..].split(',').next().unwrap().trim().parse().unwrap();
            chunks.push(Chunk { node: node.unwrap(), idx, cnt, first });
            idx += 1;
            first += cnt;
        }
    }
    // profile: (node, rec) -> (iters, cond, tlscan); only kind 0 records are listed
    let mut pr: HashMap<(usize, usize), (f64, f64, f64)> = HashMap::new();
    for (i, l) in prof.lines().enumerate() {
        if i == 0 {
            continue;
        }
        let f: Vec<&str> = l.split('\t').collect();
        let n: usize = f[0].parse().unwrap();
        let r: usize = f[1].parse().unwrap();
        let it: f64 = f[12].parse().unwrap();
        let c: f64 = f[13].parse().unwrap();
        let tl: f64 = f[14].parse().unwrap();
        pr.insert((n, r), (it, c, tl));
    }
    let mut man = fs::File::create(manifest_path).unwrap();
    writeln!(man, "module\ttheorem\tnode\tchunk\tlo\thi\tnrec\tnoncrit\titers\tcond\ttlscan\tcost").unwrap();
    for ch in chunks.iter().filter(|c| sel.is_empty() || sel.contains(&(c.node, c.idx))) {
        if ch.cnt == 0 {
            continue;
        }
        // greedy ranges (local record index inside the chunk)
        let mut ranges: Vec<(usize, usize)> = vec![];
        let (mut lo, mut cost, mut nrec) = (0usize, 0.0f64, 0usize);
        for j in 0..ch.cnt {
            let g = ch.first + j;
            let c = match pr.get(&(ch.node, g)) {
                Some(&(it, cd, tl)) => it + 0.44 * tl,
                None => 0.0,
            };
            if nrec > 0 && (cost + c > budget || nrec >= maxrec) {
                ranges.push((lo, j));
                lo = j;
                cost = 0.0;
                nrec = 0;
            }
            cost += c;
            nrec += 1;
        }
        ranges.push((lo, ch.cnt));
        let module = format!("LinesN{}C{}", ch.node, ch.idx);
        let mut s = String::new();
        s.push_str(&format!("/-\n# L4S5.{} : kernel checks of the line loops, node {}, chunk {} ({} records, {} range theorems)\nGENERATED by four_e9 emit; do not edit.\n-/\nimport LRSpectrumFull.L4S5.LinesChunk\n\nnamespace LRSpectrumFull\nnamespace L4S5\n\n", module, ch.node, ch.idx, ch.cnt, ranges.len()));
        for &(lo, hi) in &ranges {
            let (mut it, mut cd, mut tl, mut nc) = (0.0, 0.0, 0.0, 0usize);
            for j in lo..hi {
                if let Some(&(i1, c1, t1)) = pr.get(&(ch.node, ch.first + j)) {
                    it += i1;
                    cd += c1;
                    tl += t1;
                    nc += 1;
                }
            }
            let name = format!("lines_{}_{}_{}_{}", ch.node, ch.idx, lo, hi);
            s.push_str(&format!("theorem {} : linesRangeB (t1At {}) (chunkAt {} {}) {} {} = true := by decide +kernel\n", name, ch.node, ch.node, ch.idx, lo, hi));
            writeln!(man, "{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}", module, name, ch.node, ch.idx, lo, hi, hi - lo, nc, it, cd, tl, it + 0.44 * tl).unwrap();
        }
        // chunk theorem: left-nested chain
        let mut expr = format!("lines_{}_{}_{}_{}", ch.node, ch.idx, ranges[0].0, ranges[0].1);
        for &(lo, hi) in &ranges[1..] {
            expr = format!("linesRange_trans ({}) lines_{}_{}_{}_{}", expr, ch.node, ch.idx, lo, hi);
        }
        s.push_str(&format!("\ntheorem linesChunk_{}_{} : linesChunkB (t1At {}) (chunkAt {} {}) = true :=\n  linesChunk_of_range ({})\n\n", ch.node, ch.idx, ch.node, ch.node, ch.idx, expr));
        s.push_str("end L4S5\nend LRSpectrumFull\n");
        fs::write(format!("{}/{}.lean", outdir, module), s).unwrap();
    }
}
