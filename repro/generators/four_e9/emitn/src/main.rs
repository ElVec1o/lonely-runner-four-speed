// four_e9 emitn: node-check emitter (E2/E4 kernel theorems, split so that no theorem exceeds the memory line).
// For every node i of the Lean data module it writes `NodeS<i>.lean` with
//   cov_i    : covB .. = true                         (child-list coverage of the t0 range)
//   nc_i     : nodeChunks i = [chunkAt i 0, ...]      (rfl)
//   go_i_c   : goB .. = true                           (child stream of chunk c)
//   leaf_i_c_lo_hi : leafRangeB .. lo hi = true       (R records per theorem)
//   chunk_i_c, node_i                                  (glue)
// usage: emitn DATA_LEAN OUT_DIR R
use std::fs;

fn main() {
    let a: Vec<String> = std::env::args().collect();
    let data = fs::read_to_string(&a[1]).unwrap();
    let outdir = &a[2];
    let rr: usize = a[3].parse().unwrap();
    // chunks per node
    let mut nodes: Vec<Vec<usize>> = vec![];
    let mut cur: Option<usize> = None;
    for line in data.lines() {
        let t = line.trim_start();
        if let Some(rest) = t.strip_prefix("| ") {
            if let Some(num) = rest.split(" =>").next() {
                if let Ok(n) = num.trim().parse::<usize>() {
                    cur = Some(n);
                    while nodes.len() <= n {
                        nodes.push(vec![]);
                    }
                    continue;
                }
            }
        }
        if t.starts_with("{ lo := ") {
            let pos = t.find("cnt := ").unwrap() + 7;
            let cnt: usize = t[pos..].split(',').next().unwrap().trim().parse().unwrap();
            nodes[cur.unwrap()].push(cnt);
        }
    }
    for (i, chs) in nodes.iter().enumerate() {
        let mut s = String::new();
        s.push_str(&format!(
            "/-\n# L4S5.NodeS{i} : kernel checks of node {i} ({} chunk(s), {} records), split into coverage, child stream and leaf ranges\nGENERATED by four_e9 emitn; do not edit.\n-/\nimport LRSpectrumFull.L4S5.NodeSplit\n\nnamespace LRSpectrumFull\nnamespace L4S5\n\nopen LRSpectrumFull.L4S3 LRSpectrumFull.L4S4\n\nnoncomputable section\n\n",
            chs.len(),
            chs.iter().sum::<usize>()
        ));
        s.push_str(&format!(
            "theorem cov_{i} : covB (-(tmB (ctxR (t1At {i})) 0)) (nodeChunks {i}) (tmB (ctxR (t1At {i})) 0) = true := by decide +kernel\n\n"
        ));
        let list: Vec<String> = (0..chs.len()).map(|c| format!("chunkAt {i} {c}")).collect();
        s.push_str(&format!("theorem nc_{i} : nodeChunks {i} = [{}] := rfl\n\n", list.join(", ")));
        for (c, &cnt) in chs.iter().enumerate() {
            s.push_str(&format!(
                "theorem go_{i}_{c} : goB (ctxR (t1At {i})) (cands (ctxR (t1At {i})) (chunkAt {i} {c}).lo (chunkAt {i} {c}).hi) (stOf (chunkAt {i} {c}).bl (chunkAt {i} {c}).cnt) = true := by decide +kernel\n\n"
            ));
            let mut ranges: Vec<(usize, usize)> = vec![];
            let mut lo = 0;
            while lo < cnt {
                let hi = (lo + rr).min(cnt);
                ranges.push((lo, hi));
                lo = hi;
            }
            if ranges.is_empty() {
                ranges.push((0, 0));
            }
            for &(lo, hi) in &ranges {
                s.push_str(&format!(
                    "theorem leaf_{i}_{c}_{lo}_{hi} : leafRangeB (t1At {i}) (chunkAt {i} {c}) {lo} {hi} = true := by decide +kernel\n"
                ));
            }
            let mut expr = format!("leaf_{i}_{c}_{}_{}", ranges[0].0, ranges[0].1);
            for &(lo, hi) in &ranges[1..] {
                expr = format!("leafRange_trans ({expr}) leaf_{i}_{c}_{lo}_{hi}");
            }
            s.push_str(&format!(
                "\ntheorem chunk_{i}_{c} : chunkB (t1At {i}) (chunkAt {i} {c}) = true :=\n  chunkB_of_parts _ _ go_{i}_{c} ({expr})\n\n"
            ));
        }
        let names: Vec<String> = (0..chs.len()).map(|c| format!("chunk_{i}_{c}")).collect();
        s.push_str(&format!(
            "theorem node_{i} : nodeB (t1At {i}) (nodeChunks {i}) = true := by\n  unfold nodeB\n  rw [Bool.and_eq_true]\n  refine ⟨cov_{i}, ?_⟩\n  rw [nc_{i}]\n  simp [List.all_cons, {}]\n\nend\n\nend L4S5\nend LRSpectrumFull\n",
            names.join(", ")
        ));
        fs::write(format!("{}/NodeS{}.lean", outdir, i), s).unwrap();
    }
}
