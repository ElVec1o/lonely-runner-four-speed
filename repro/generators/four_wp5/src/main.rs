// four_wp5 emitter: cert4 v1 binary files (four_wp0 cert_final) -> Lean data module LRSpectrumFull/L4S5/Data.lean
// usage: four_wp5 CERT_DIR OUT_LEAN MAXREC
// Leaf record = 46 fields, each field f in [-112,112] stored as byte f+128; a blob = up to 100 records concatenated
// (little endian Nat); chunks of a node = consecutive t0 ranges holding at most MAXREC records.
use std::fmt::Write;
use std::fs;

fn read_ints(p: &str) -> Vec<i32> {
    let b = fs::read(p).unwrap();
    b.chunks(4).map(|c| i32::from_le_bytes([c[0], c[1], c[2], c[3]])).collect()
}
fn isqrt(n: i128) -> i128 {
    if n <= 0 {
        return 0;
    }
    let mut x = (n as f64).sqrt() as i128;
    while x * x > n {
        x -= 1;
    }
    while (x + 1) * (x + 1) <= n {
        x += 1;
    }
    x
}
fn wmin(x: &[i32], w: i64) -> i64 {
    let mut m = i64::MAX;
    for &xi in x {
        let r = (xi as i64).rem_euclid(w);
        m = m.min(r.min(w - r));
    }
    m
}
fn v4(x: &[i32]) -> String {
    format!("![{}, {}, {}, {}]", x[0], x[1], x[2], x[3])
}
fn hex_of(bytes: &[u8]) -> String {
    let mut s = String::from("0x");
    let mut started = false;
    for &b in bytes.iter().rev() {
        if !started && b == 0 {
            continue;
        }
        if !started {
            write!(s, "{:x}", b).unwrap();
            started = true;
        } else {
            write!(s, "{:02x}", b).unwrap();
        }
    }
    if !started {
        s.push('0');
    }
    s
}
fn main() {
    let a: Vec<String> = std::env::args().collect();
    let dir = &a[1];
    let out = &a[2];
    let maxrec: usize = a[3].parse().unwrap();
    let t1 = read_ints(&format!("{}/t1.bin", dir));
    assert_eq!(t1.len(), 15 * 37);
    let t5 = read_ints(&format!("{}/t5.bin", dir));
    assert_eq!(t5.len() % 9, 0);
    let mut s = String::new();
    s.push_str("/-\n# L4S5.Data : the frozen certificate cert4 v1 (MID variant) as Lean data (GENERATED by four_wp5; do not edit)\n\n");
    s.push_str("Depth-1 records (`t1Data`, 15), residual tuples (`t5Data`), leaf records as packed blobs (`nodeChunks`).\n");
    s.push_str("A leaf record is 46 fields, field f stored as the byte f + 128; a blob is at most 100 records, little endian.\n");
    s.push_str("No `sorry`, no `native_decide`, no axiom.  Not registered in any aggregator.\n-/\n");
    s.push_str("import LRSpectrumFull.L4S5.Defs\n\nnamespace LRSpectrumFull\nnamespace L4S5\n\nopen LRSpectrumFull.L4S3 LRSpectrumFull.L4S4\n\n");
    // T1
    s.push_str("def t1Data : List T1Rec4 := [\n");
    for k in 0..15 {
        let r = &t1[k * 37..(k + 1) * 37];
        let h = &r[0..4];
        let x1 = &r[4..8];
        let w1 = r[8];
        let b: Vec<String> = (0..3).map(|j| v4(&r[9 + 4 * j..13 + 4 * j])).collect();
        let rr: Vec<String> = (0..3).map(|j| v4(&r[21 + 4 * j..25 + 4 * j])).collect();
        let sv = &r[33..37];
        write!(s, "  {{ h := {}, x1 := {}, W1 := {}, b := ![{}], r := ![{}], s := {} }}{}\n", v4(h), v4(x1), w1,
            b.join(", "), rr.join(", "), v4(sv), if k < 14 { "," } else { "" }).unwrap();
    }
    s.push_str("]\n\n");
    // T5
    s.push_str("def t5Data : List T5Rec4 := [\n");
    let n5 = t5.len() / 9;
    for k in 0..n5 {
        let r = &t5[k * 9..(k + 1) * 9];
        write!(s, "  {{ v := {}, kind := {}, a := {}, q := {}, mln := {}, mld := {} }}{}\n", v4(&r[0..4]), r[4], r[5], r[6],
            r[7], r[8], if k + 1 < n5 { "," } else { "" }).unwrap();
    }
    s.push_str("]\n\n");
    // chunks
    s.push_str("def nodeChunks : ℕ → List Chunk\n");
    let mut stats = String::new();
    for k in 0..15 {
        let r = &t1[k * 37..(k + 1) * 37];
        let w1 = r[8] as i64;
        let a1 = 4 * wmin(&r[4..8], w1) - w1;
        assert!(a1 > 0);
        let b0: Vec<i128> = (0..3).map(|j| {
            let bj = &r[9 + 4 * j..13 + 4 * j];
            bj.iter().map(|&x| (x as i128) * (x as i128)).sum()
        }).collect();
        let t0max = isqrt(28 * (w1 as i128) * (w1 as i128) * b0[0] / (3 * (a1 as i128) * (a1 as i128)));
        let leaf = read_ints(&format!("{}/leaf_{:02}.bin", dir, k));
        assert_eq!(leaf.len() % 46, 0);
        let n = leaf.len() / 46;
        // group by t0
        let mut chunks: Vec<(i128, i128, usize, usize)> = vec![]; // lo, hi, first record, count
        let mut lo = -t0max;
        let mut first = 0usize;
        let mut cur = 0usize;
        let mut t0 = -t0max;
        let mut idx = 0usize;
        while t0 <= t0max {
            let mut c = 0usize;
            while idx + c < n && leaf[(idx + c) * 46] as i128 == t0 {
                c += 1;
            }
            assert!(c <= maxrec, "one t0 slice exceeds MAXREC");
            if cur + c > maxrec {
                chunks.push((lo, t0 - 1, first, cur));
                lo = t0;
                first = idx;
                cur = 0;
            }
            cur += c;
            idx += c;
            t0 += 1;
        }
        assert_eq!(idx, n, "records outside the t0 range or not sorted");
        chunks.push((lo, t0max, first, cur));
        write!(s, "  | {} => [\n", k).unwrap();
        for (ci, &(lo, hi, f, cnt)) in chunks.iter().enumerate() {
            let mut blobs: Vec<String> = vec![];
            let mut rec = 0;
            while rec < cnt {
                let m = (cnt - rec).min(100);
                let mut bytes: Vec<u8> = vec![];
                for q in 0..m {
                    let base = (f + rec + q) * 46;
                    for fld in 0..46 {
                        let v = leaf[base + fld];
                        assert!((-128..=127).contains(&v));
                        bytes.push((v + 128) as u8);
                    }
                }
                blobs.push(hex_of(&bytes));
                rec += m;
            }
            write!(s, "    {{ lo := {}, hi := {}, cnt := {}, bl := [{}] }}{}\n", lo, hi, cnt, blobs.join(", "),
                if ci + 1 < chunks.len() { "," } else { "" }).unwrap();
        }
        s.push_str("  ]\n");
        writeln!(stats, "node {} T0={} records={} chunks={:?}", k, t0max, n, chunks.iter().map(|c| (c.0 as i64, c.1 as i64, c.3)).collect::<Vec<_>>()).unwrap();
    }
    s.push_str("  | _ => []\n\nend L4S5\nend LRSpectrumFull\n");
    fs::write(out, s).unwrap();
    eprint!("{}", stats);
}
